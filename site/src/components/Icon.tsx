import {
  Atom,
  Award,
  BookOpen,
  Briefcase,
  Calculator,
  Calendar,
  Camera,
  ClipboardList,
  Compass,
  Flag,
  FlaskConical,
  GraduationCap,
  Heart,
  Landmark,
  Languages,
  Leaf,
  Library,
  Lightbulb,
  Mic,
  Monitor,
  Newspaper,
  PenLine,
  Shield,
  Sparkles,
  Target,
  Trophy,
  Users,
  type LucideIcon,
} from 'lucide-react'

const icons: Record<string, LucideIcon> = {
  atom: Atom,
  award: Award,
  book: BookOpen,
  briefcase: Briefcase,
  calculator: Calculator,
  calendar: Calendar,
  camera: Camera,
  clipboard: ClipboardList,
  compass: Compass,
  flag: Flag,
  flask: FlaskConical,
  graduation: GraduationCap,
  heart: Heart,
  landmark: Landmark,
  languages: Languages,
  leaf: Leaf,
  library: Library,
  lightbulb: Lightbulb,
  mic: Mic,
  monitor: Monitor,
  newspaper: Newspaper,
  pen: PenLine,
  shield: Shield,
  sparkles: Sparkles,
  target: Target,
  trophy: Trophy,
  users: Users,
}

export function Icon({ name, className }: { name?: string; className?: string }) {
  const C = (name && icons[name]) || BookOpen
  return <C className={className} aria-hidden="true" />
}
